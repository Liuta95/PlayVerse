// Generates src/tokens/tokens.css from src/tokens/tokens.json (W3C DTCG, exported from Figma Variables).
// Token path → CSS variable: path segments joined with "-", kebab-cased
// (color.gray.900 → --color-gray-900). Aliases like "{color.gray.900}" become var(--color-gray-900).
// Fails the build on a broken alias or on two tokens that map to the same CSS variable.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'src/tokens/tokens.json');
const out = resolve(root, 'src/tokens/tokens.css');

const kebab = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[\s_/.]+/g, '-')
    .toLowerCase();

const toVar = (path) => `--${path.map(kebab).join('-')}`;

const tokens = new Map(); // dotted path -> token
const walk = (node, path) => {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$') || child === null || typeof child !== 'object') continue;
    if ('$value' in child) tokens.set([...path, key].join('.'), { path: [...path, key], ...child });
    else walk(child, [...path, key]);
  }
};
walk(JSON.parse(readFileSync(src, 'utf8')), []);

const formatValue = (token) => {
  const { $value: value, $type: type } = token;
  if (typeof value === 'string') {
    const resolved = value.replace(/\{([^}]+)\}/g, (_, ref) => {
      if (!tokens.has(ref)) throw new Error(`${token.path.join('.')}: unknown alias {${ref}}`);
      return `var(${toVar(ref.split('.'))})`;
    });
    // Font family names contain spaces (e.g. Space Grotesk) → quote them.
    return type === 'fontFamily' && !value.startsWith('{') ? `"${resolved}"` : resolved;
  }
  if (typeof value === 'number') return String(value);
  // DTCG dimension object, e.g. { "value": 16, "unit": "px" }
  if (value && typeof value === 'object' && 'value' in value && 'unit' in value) {
    return `${value.value}${value.unit}`;
  }
  throw new Error(`${token.path.join('.')}: unsupported token value ${JSON.stringify(value)}`);
};

const seen = new Map();
const lines = [];
let lastGroup = null;
for (const token of tokens.values()) {
  const name = toVar(token.path);
  if (seen.has(name)) {
    throw new Error(`CSS variable clash: ${name} ← ${seen.get(name)} and ${token.path.join('.')}`);
  }
  seen.set(name, token.path.join('.'));
  const group = token.path[0];
  if (lastGroup !== null && group !== lastGroup) lines.push('');
  lastGroup = group;
  lines.push(`  ${name}: ${formatValue(token)};`);
}

writeFileSync(
  out,
  `/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`,
);
console.log(`tokens.css: ${tokens.size} tokens`);
