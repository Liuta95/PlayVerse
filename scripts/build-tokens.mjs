// Generates src/tokens/tokens.css from src/tokens/tokens.json (W3C DTCG).
// Token path → CSS variable: group/name segments joined with "-", kebab-cased
// (color/primary/default → --color-primary-default). Aliases like "{color.primary}"
// become var(--color-primary).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'src/tokens/tokens.json');
const out = resolve(root, 'src/tokens/tokens.css');

const kebab = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/[\s_/.]+/g, '-')
    .toLowerCase();

const toVar = (path) => `--${path.map(kebab).join('-')}`;

const formatValue = (value) => {
  if (typeof value === 'string') {
    return value.replace(/\{([^}]+)\}/g, (_, ref) => `var(${toVar(ref.split('.'))})`);
  }
  if (typeof value === 'number') return String(value);
  // DTCG dimension object, e.g. { "value": 16, "unit": "px" }
  if (value && typeof value === 'object' && 'value' in value && 'unit' in value) {
    return `${value.value}${value.unit}`;
  }
  throw new Error(`Unsupported token value: ${JSON.stringify(value)}`);
};

const lines = [];
const walk = (node, path) => {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$') || child === null || typeof child !== 'object') continue;
    if ('$value' in child) {
      lines.push(`  ${toVar([...path, key])}: ${formatValue(child.$value)};`);
    } else {
      walk(child, [...path, key]);
    }
  }
};

walk(JSON.parse(readFileSync(src, 'utf8')), []);

writeFileSync(
  out,
  `/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`,
);
console.log(`tokens.css: ${lines.length} tokens`);
